test("cari alamat di peta: saran muncul sambil mengetik, memilih saran memindahkan peta, titik rumah tetap diketuk sendiri", async ({ page }) => {
  let asked = ""
  await page.route("https://photon.komoot.io/**", route => {
    asked = route.request().url()
    return route.fulfill({ json: { type: "FeatureCollection", features: [
      { type: "Feature", geometry: { type: "Point", coordinates: [107.4433, -6.5569] }, properties: { name: "Perumahan Uji", type: "other", district: "Uji Barat", city: "Purwakarta", state: "Jawa Barat" } },
      { type: "Feature", geometry: { type: "Point", coordinates: [107.61, -6.9] }, properties: { name: "Jalan Uji", type: "street", city: "Bandung", state: "Jawa Barat" } },
    ] } })
  })
  await loginUi(page, "admin@e2e.test")
  await page.goto("/client/baru")
  const search = page.getByRole("combobox", { name: "Cari alamat di peta" })
  await search.fill("pe")
  await expect(page.getByRole("listbox", { name: "Saran alamat" })).toHaveCount(0)
  await search.fill("perum uji")
  const options = page.getByRole("option")
  await expect(options).toHaveCount(2)
  await expect(options.first()).toContainText("Perumahan Uji")
  await expect(options.first()).toContainText("Uji Barat, Purwakarta, Jawa Barat")
  await expect(options.nth(1)).toContainText("Bandung, Jawa Barat")
  expect(asked).toContain("bbox=95,-11,141.1,6.1")
  expect(asked).toContain("q=perum%20uji")

  await search.press("ArrowDown")
  await expect(options.nth(1)).toHaveAttribute("aria-selected", "true")
  await search.press("ArrowUp")
  await search.press("Enter")
  await expect(search).toHaveValue("Perumahan Uji")
  await expect(page.getByRole("listbox", { name: "Saran alamat" })).toHaveCount(0)
  await expect(page.getByText("Ketuk peta di lokasi rumah untuk menandai titiknya.")).toBeVisible()
  await page.getByTestId("peta").click()
  await expect(page.getByText(/^Titik: -6\.556\d*, 107\.443\d*/)).toBeVisible()
})
