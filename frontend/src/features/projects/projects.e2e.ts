import { expect, test } from "@playwright/test"
import { call, invoicedProject, loginUi, newClient, newGuest, saveSimulation, submitSimulation, uniqueEmail } from "../../test/e2e"

test("admin membuat client dan proyek baru dari layar, langsung di Planning dengan password sementara", async ({ page }) => {
  await loginUi(page, "admin@e2e.test")
  await page.goto("/client")
  await page.getByRole("link", { name: "Client atau proyek baru" }).click()
  await page.getByLabel("Nama client").fill("Pak Joko")
  await page.getByLabel("Email client").fill(uniqueEmail())
  await page.getByLabel("Nomor WhatsApp client").fill("081300001111")
  await page.getByLabel("Alamat pemasangan").fill("Jl. Melati 2")
  await page.getByLabel("Kota").fill("Cimahi")
  await page.getByRole("button", { name: "Buat proyek" }).click()
  await expect(page.getByRole("heading", { name: /^Proyek PLTS-\d{4}-\d{3} dibuat$/ })).toBeVisible()
  await expect(page.getByText(/Password sementara client: \S{12}\./)).toBeVisible()
  await page.getByRole("link", { name: "Buka planning" }).click()
  await expect(page.getByRole("heading", { name: "Planning (draf)" })).toBeVisible()
  await expect(page.locator(".head .sub b")).toHaveText("Planning")
  await page.goto("/client?q=Pak%20Joko")
  await expect(page.locator("table.data tbody tr")).toContainText(["Pak Joko"])
})

test("admin meninjau pengajuan: tolak wajib dengan alasan, terima menjadikan guest client di Planning", async ({ page, request }) => {
  const a = await newGuest(request, "Guest Ditolak"), b = await newGuest(request, "Guest Diterima")
  const pa = await submitSimulation(request, a.token), pb = await submitSimulation(request, b.token)
  await loginUi(page, "admin@e2e.test")
  await page.goto(`/client/${pa.id}`)
  await expect(page.getByRole("heading", { name: "Tinjau pengajuan" })).toBeVisible()
  await page.getByRole("button", { name: "Tolak", exact: true }).click()
  await page.getByLabel("Alasan penolakan").fill("Di luar area layanan")
  await page.getByRole("button", { name: "Tolak pengajuan" }).click()
  await expect(page.locator(".head .sub b")).toHaveText("Ditolak")
  await expect(page.getByText("Pengajuan ditolak: Di luar area layanan")).toBeVisible()

  await page.goto(`/client/${pb.id}`)
  await page.getByRole("button", { name: "Terima pengajuan" }).click()
  await expect(page.locator(".head .sub b")).toHaveText("Planning")
  await page.getByRole("button", { name: "Planning", exact: true }).click()
  await expect(page.getByRole("region", { name: "Part" }).locator("tbody tr")).toHaveCount(3)
})

test("skenario 1: client A tidak bisa membuka data, tagihan, atau simulasi proyek client B dengan mengganti alamat", async ({ page, request }) => {
  const a = await newClient(request, "Client A"), b = await invoicedProject(request, "Client B")
  await loginUi(page, a.email)
  await page.goto(`/status-pengerjaan?proyek=${b.project.id}`)
  await expect(page.getByRole("heading", { name: `Proyek ${a.project.code}` })).toBeVisible()
  await expect(page.getByText(b.project.code)).toHaveCount(0)
  await expect(page.getByText(b.invoice.number)).toHaveCount(0)
  await page.goto(`/invoice-pembelian?proyek=${b.project.id}`)
  await expect(page.getByRole("heading", { name: "Rincian belanja" })).toBeVisible()
  await expect(page.getByText(b.project.code)).toHaveCount(0)
  await page.goto(`/simulator/${(b.project as { simulation_id?: string }).simulation_id}`)
  await expect(page.getByRole("alert")).toHaveText("Simulasi tidak ditemukan")
  await page.goto(`/client/${b.project.id}`)
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByText("Halaman itu tidak bisa dibuka dengan akun Anda.")).toBeVisible()
})

test("guest menandai lokasi pemasangan di peta saat mengajukan, admin melihat titiknya dan bisa membukanya di Google Maps", async ({ page, browser, request }) => {
  const g = await newGuest(request, "Guest Peta")
  const sim = await saveSimulation(request, g.token)
  await loginUi(page, g.email)
  await page.goto(`/simulator/${sim.id}`)
  await page.getByRole("button", { name: "Lanjutkan ke perhitungan detail" }).click()
  await page.getByLabel("Alamat pemasangan").fill("Jl. Kenanga 8")
  await page.getByLabel("Kota").fill("Purwakarta")
  await page.getByTestId("peta").click({ position: { x: 200, y: 150 } })
  await expect(page.getByText(/^Titik: -?\d+\.\d+, \d+\.\d+/)).toBeVisible()
  await page.getByRole("button", { name: "Kirim pengajuan" }).click()
  await expect(page.getByText("Permintaan Anda sedang ditinjau")).toBeVisible()

  const project = (await call(request, "GET", "/api/home", { token: g.token })).projects[0]
  const admin = await (await browser.newContext({ baseURL: "http://localhost:5174" })).newPage()
  await loginUi(admin, "admin@e2e.test")
  await admin.goto("/client")
  await admin.locator("tr", { hasText: project.code }).getByRole("link", { name: "Buka" }).click()
  await expect(admin.getByRole("heading", { name: "Tinjau pengajuan" })).toBeVisible()
  await expect(admin.getByRole("link", { name: "Buka di Google Maps" })).toHaveAttribute("href", /^https:\/\/www\.google\.com\/maps\?q=-?\d+\.\d+,\d+\.\d+$/)
})

